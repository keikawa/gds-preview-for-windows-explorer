// Development-only, dependency-free Glasbey-style greedy palette generation.
// No part of this script runs in the application or in a normal build.
// Sources and limitations: docs/LAYER-COLORS.md.
import { readFileSync } from 'node:fs';

const target = new URL('../src/GdsPreview.Renderer/LayerPalette.Generated.cs', import.meta.url);
const seeds = ['77AADD', 'EE8866', 'EEDD88', 'FFAABB', '99DDFF',
    '44BB99', 'BBCC33', 'AAAA00', 'DDDDDD'].map(x => parseInt(x, 16));
const backgrounds = [0x181B20, 0x1F232A];
const alpha = 128 / 255;
const decode = x => (x /= 255) <= .04045 ? x / 12.92 : ((x + .055) / 1.055) ** 2.4;
const linear = rgb => [rgb >>> 16, rgb >>> 8 & 255, rgb & 255].map(decode);
const luminance = rgb => .2126 * rgb[0] + .7152 * rgb[1] + .0722 * rgb[2];
const blend = (fg, bg) => fg.map((x, i) => alpha * x + (1 - alpha) * bg[i]);

// Bjorn Ottosson's public-domain linear-sRGB -> Oklab transform (2021 matrices).
function lab([r, g, b]) {
    const l = Math.cbrt(.4122214708 * r + .5363325363 * g + .0514459929 * b);
    const m = Math.cbrt(.2119034982 * r + .6806995451 * g + .1073969566 * b);
    const s = Math.cbrt(.0883024619 * r + .2817188376 * g + .6299787005 * b);
    return [.2104542553 * l + .7936177850 * m - .0040720468 * s,
        1.9779984951 * l - 2.4285922050 * m + .4505937099 * s,
        .0259040371 * l + .7827717662 * m - .8086757660 * s];
}

function describe(rgb) {
    const source = linear(rgb);
    const [, a, b] = lab(source);
    const composites = backgrounds.map(x => blend(source, linear(x)));
    return { rgb, chroma: Math.hypot(a, b), y: luminance(source),
        contrast: Math.min(...composites.map((x, i) =>
            (luminance(x) + .05) / (luminance(linear(backgrounds[i])) + .05))),
        labs: composites.map(lab), nearest: Infinity };
}

function distance(a, b) {
    // Maximise the worst separation on either actual canvas, after compositing.
    return Math.min(...a.labs.map((p, i) =>
        p.reduce((sum, x, j) => sum + (x - b.labs[i][j]) ** 2, 0)));
}

const selected = seeds.map(describe);
const candidates = [];
const levels = [...Array.from({ length: 32 }, (_, i) => i * 8), 255];
for (const r of levels) for (const g of levels) for (const b of levels) {
    const color = describe(r << 16 | g << 8 | b);
    // Exclude near-neutral additions, dark colours and very bright/high-chroma
    // fills. Keep the nine published seeds unmodified (including their grey).
    if (color.contrast >= 3.15 && color.y <= .73 &&
        color.chroma >= .055 && color.chroma <= .20 && !seeds.includes(color.rgb))
        candidates.push(color);
}
for (const seed of selected)
    for (const color of candidates) color.nearest = Math.min(color.nearest, distance(color, seed));
while (selected.length < 256) {
    let best = candidates[0];
    for (const color of candidates) if (color.nearest > best.nearest) best = color;
    if (!(best.nearest > 0)) throw new Error('Not enough unique palette candidates.');
    selected.push(best);
    for (const color of candidates) color.nearest = Math.min(color.nearest, distance(color, best));
}

const lines = [];
for (let i = 0; i < selected.length; i += 8)
    lines.push('        ' + selected.slice(i, i + 8).map(x =>
        '0x' + x.rgb.toString(16).toUpperCase().padStart(6, '0')).join(', ') + ',');
const source = `// <auto-generated />
// Generated by scripts/generate-layer-palette.mjs. See docs/LAYER-COLORS.md.
// Stable RGB table: changing values or order changes cross-file colour identity.
namespace GdsPreview.Renderer;

internal static partial class LayerPalette
{
    private static readonly int[] Rgb =
    [
${lines.join('\n')}
    ];
}
`;
const mode = process.argv[2] ?? '--check';
if (mode === '--print') process.stdout.write(source);
else if (mode === '--check') {
    if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== source)
        throw new Error('LayerPalette.Generated.cs differs from the deterministic generator.');
    console.log(`PASS: 256 reproducible colours, minimum full-coverage contrast ${
        Math.min(...selected.map(x => x.contrast)).toFixed(4)}:1.`);
} else throw new Error('Usage: node scripts/generate-layer-palette.mjs [--check|--print]');
